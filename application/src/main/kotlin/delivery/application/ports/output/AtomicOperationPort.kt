package delivery.application.ports.output

import arrow.core.Either

/**
 * Выполняет бизнес-операцию в атомарной транзакции.
 *
 * Порт был введен из-за ограничения декларативного управления транзакциями Spring.
 * Аннотация `@Transactional` откатывает транзакцию только при выбрасывании
 * исключения, тогда как приложение использует типизированные бизнес-ошибки
 * через [Either], не нарушая обычный поток выполнения.
 *
 * Если операция возвращает [Either.Left], адаптер инфраструктуры помечает
 * текущую транзакцию на откат (`rollback`), сохраняя при этом типизированную
 * бизнес-ошибку без преобразования её в исключение.
 */
interface AtomicOperationPort {
    /**
     * Выполняет операцию в атомарной транзакции.
     *
     * - [Either.Right] — транзакция фиксируется (`commit`).
     * - [Either.Left] — транзакция откатывается (`rollback`), а ошибка
     *   возвращается вызывающему коду.
     */
    fun <E, T> execute(block: () -> Either<E, T>): Either<E, T>
}
